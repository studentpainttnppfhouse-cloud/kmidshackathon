/**
 * Forms built and answered inside the portal.
 *
 * The builder posts its questions as a JSON string in one hidden field, because
 * a question list is a tree and a form body is flat. That string is *not*
 * trusted for being generated by our own UI — it is parsed with the same zod
 * schema an attacker's hand-written payload would face, and anything that does
 * not fit the schema is refused rather than coerced.
 */

const metaSchema = z.object({
  title: z.string().trim().min(2, "Name the form.").max(200),
  description: z.string().trim().max(1000).optional().or(z.literal("")),
  departmentId: z.string().optional().or(z.literal("")),
  deadline: z.string().max(20).optional().or(z.literal("")),
  isOpen: z.coerce.boolean().optional(),
});

/** Turns the builder's JSON into a checked definition, or an error message. */
function readDefinition(raw: string): { ok: true; value: FormDefinition } | { ok: false; error: string } {
  let json: unknown;
  try {
    json = JSON.parse(raw);
  } catch {
    return { ok: false, error: "The question list could not be read. Reload the page and try again." };
  }

  const parsed = formDefinitionSchema.safeParse(json);
  if (!parsed.success) {
    return { ok: false, error: parsed.error.issues[0]?.message ?? "That form is not valid." };
  }

  const problem = checkDefinition(parsed.data);
  if (problem) return { ok: false, error: problem };

  return { ok: true, value: parsed.data };
}

/** A readable, unique URL for the fill page. */
async function uniqueSlug(title: string, excludeId?: string): Promise<string> {
  const base =
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40) || "form";

  for (let attempt = 0; attempt < 40; attempt += 1) {
    const candidate = attempt === 0 ? base : `${base}-${attempt + 1}`;
    const clash = await db.form.findUnique({ where: { slug: candidate }, select: { id: true } });
    if (!clash || clash.id === excludeId) return candidate;
  }

  return `${base}-${Date.now().toString(36)}`;
}

function parseDeadline(value: string | undefined): Date | null {
  if (!value) return null;
  const date = new Date(`${value}T23:59:59+07:00`);
  return Number.isNaN(date.getTime()) ? null : date;
}

